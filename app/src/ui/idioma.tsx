export const traducirTexto = (idioma: Idioma, texto: string, vars?: Variables): string => {
  const base = idioma === 'en' ? INGLES[texto] ?? texto : texto;
  if (!vars) return base;
  return base.replace(/\{(\w+)\}/g, (m, k: string) => (vars[k] !== undefined ? String(vars[k]) : m));
};

interface ContextoIdioma {
  idioma: Idioma;
  /** No hay preferencia guardada: se muestra el aviso inicial. */
  sinElegir: boolean;
  cambiarIdioma: (idioma: Idioma) => void;
  t: (texto: string, vars?: Variables) => string;
}

const Ctx = createContext<ContextoIdioma>({
  idioma: 'es', sinElegir: false, cambiarIdioma: () => {}, t: (texto) => texto,
});

export function useIdioma(): ContextoIdioma {
  return useContext(Ctx);
}

/** Atajo para componentes: `const t = useT();`. */
export function useT() {
  return useIdioma().t;
}

export function IdiomaProvider({ children }: { children: ReactNode }) {
  const [idioma, setIdioma] = useState<Idioma>(() => leerIdiomaGuardado() ?? 'es');
  const [sinElegir, setSinElegir] = useState<boolean>(() => leerIdiomaGuardado() === null);

  useEffect(() => {
    document.documentElement.lang = idioma;
  }, [idioma]);

  const cambiarIdioma = useCallback((nuevo: Idioma) => {
    setIdioma(nuevo);
    guardarIdioma(nuevo);
    setSinElegir(false);
  }, []);

  const t = useCallback((texto: string, vars?: Variables) => traducirTexto(idioma, texto, vars), [idioma]);

  const valor = useMemo(() => ({ idioma, sinElegir, cambiarIdioma, t }), [idioma, sinElegir, cambiarIdioma, t]);

  return (
    <Ctx.Provider value={valor}>
      {children}
      {sinElegir && <AvisoIdioma onElegir={cambiarIdioma} />}
    </Ctx.Provider>
  );
}

