/** Selector compacto para la barra superior (solo español o inglés). */
export function SelectorIdioma({ compacto = true }: { compacto?: boolean }) {
  const { idioma, cambiarIdioma } = useIdioma();
  return (
    <div className="selector-idioma" role="group" aria-label={idioma === 'es' ? 'Cambiar idioma' : 'Change language'}>
      {!compacto && <span className="selector-idioma-etiqueta">{idioma === 'es' ? 'Idioma' : 'Language'}</span>}
      {IDIOMAS.map((i) => (
        <button
          key={i.id}
          type="button"
          lang={i.id}
          aria-pressed={idioma === i.id}
          className={idioma === i.id ? 'activo' : ''}
          onClick={() => cambiarIdioma(i.id)}
          title={idioma === 'es' ? `Idioma: ${i.nombre}` : `Language: ${i.nombre}`}
        >
          {i.corto}
        </button>
      ))}
    </div>
  );
}
